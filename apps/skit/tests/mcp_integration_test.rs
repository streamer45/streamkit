#[tokio::test]
async fn mcp_config_endpoint_validation() {
    // Verify that McpConfig::validate rejects bad endpoints at config-load time
    let mut mcp_config = streamkit_server::config::McpConfig {
        enabled: false,
        endpoint: "/bad/path".to_string(),
        ..Default::default()
    };
    assert!(mcp_config.validate().is_ok());

    // Enabled with bad prefix should fail
    mcp_config.enabled = true;
    mcp_config.endpoint = "/bad/path".to_string();
    assert!(mcp_config.validate().is_err());

    // Auth bypass path should fail
    mcp_config.endpoint = "/api/v1/auth/mcp".to_string();
    assert!(mcp_config.validate().is_err());

    // Path traversal should fail
    mcp_config.endpoint = "/api/v1/../mcp".to_string();
    assert!(mcp_config.validate().is_err());

    // Only /api/ prefix should fail (missing version/mcp segments)
    mcp_config.endpoint = "/api/".to_string();
    assert!(mcp_config.validate().is_err());

    // Non-versioned path should fail
    mcp_config.endpoint = "/api/mcp".to_string();
    assert!(mcp_config.validate().is_err());

    // Colliding with existing routes should fail (wrong third segment)
    mcp_config.endpoint = "/api/v1/sessions".to_string();
    assert!(mcp_config.validate().is_err());

    // Valid default endpoint should pass
    mcp_config.endpoint = "/api/v1/mcp".to_string();
    assert!(mcp_config.validate().is_ok());

    // Valid with subpath should pass
    mcp_config.endpoint = "/api/v2/mcp/extra".to_string();
    assert!(mcp_config.validate().is_ok());
}

