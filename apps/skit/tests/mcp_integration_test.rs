#[tokio::test]
async fn mcp_validate_pipeline_returns_diagnostics() {
    let _ = tracing_subscriber::fmt::try_init();

    let (addr, _handle, token, _dir) = start_mcp_server().await;
    let client = reqwest::Client::new();

    let session_id = init_mcp_session(&client, addr, &token).await;

    // Call validate_pipeline with invalid YAML
    let validate = json!({
        "jsonrpc": "2.0",
        "id": 2,
        "method": "tools/call",
        "params": {
            "name": "validate_pipeline",
            "arguments": {
                "yaml": "not: valid: yaml: [["
            }
        }
    });
    let res = mcp_post_with_session(&client, addr, &validate, &token, &session_id).await;
    assert_eq!(res.status(), StatusCode::OK);

    // Response is SSE stream — extract JSON-RPC result from `data:` lines.
    let body_text = res.text().await.expect("failed to read response body");
    let body = extract_sse_json(&body_text);
    let result = &body["result"];
    assert!(!result.is_null(), "expected result in response, got: {body}");

    // The tool should return text content with validation diagnostics
    let content = &result["content"][0]["text"];
    assert!(content.is_string(), "expected text content in result");
    let text = content.as_str().unwrap();
    let parsed: serde_json::Value = serde_json::from_str(text).expect("tool output not valid JSON");
    assert_eq!(parsed["valid"], false);
    assert!(!parsed["errors"].as_array().unwrap().is_empty());
}

#[tokio::test]
async fn mcp_create_session_permission_denied() {
    let _ = tracing_subscriber::fmt::try_init();

    let (addr, _handle, token, _dir) = start_restricted_mcp_server().await;
    let client = reqwest::Client::new();

    let session_id = init_mcp_session(&client, addr, &token).await;

    // Try to create a session — should be denied by permissions
    let create = json!({
        "jsonrpc": "2.0",
        "id": 2,
        "method": "tools/call",
        "params": {
            "name": "create_session",
            "arguments": {
                "yaml": "nodes:\n  tone:\n    kind: streamkit::tone_generator\n    params:\n      frequency: 440\n      sample_rate: 48000\n      duration: 1.0",
                "name": "test-denied"
            }
        }
    });
    let res = mcp_post_with_session(&client, addr, &create, &token, &session_id).await;
    assert_eq!(res.status(), StatusCode::OK);

    let body_text = res.text().await.expect("failed to read response body");
    let body = extract_sse_json(&body_text);
    let error = &body["error"];
    assert!(!error.is_null(), "expected error in response, got: {body}");
    let error_msg = error["message"].as_str().unwrap_or("");
    assert!(
        error_msg.contains("Permission denied") || error_msg.contains("permission"),
        "expected permission error, got: {error_msg}"
    );
}

