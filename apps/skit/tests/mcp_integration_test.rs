/// Send a JSON-RPC request to the MCP endpoint.
async fn mcp_post(
    client: &reqwest::Client,
    addr: SocketAddr,
    body: &serde_json::Value,
    auth_header: Option<&str>,
) -> reqwest::Response {
    let mut req = client
        .post(format!("http://{addr}/api/v1/mcp"))
        .header(CONTENT_TYPE, "application/json")
        .header(ACCEPT, "application/json, text/event-stream")
        .json(body);

    if let Some(token) = auth_header {
        req = req.header(AUTHORIZATION, format!("Bearer {token}"));
    }

    req.send().await.expect("Failed to send MCP request")
}

/// Send a JSON-RPC request with a session ID.
async fn mcp_post_with_session(
    client: &reqwest::Client,
    addr: SocketAddr,
    body: &serde_json::Value,
    token: &str,
    session_id: &str,
) -> reqwest::Response {
    client
        .post(format!("http://{addr}/api/v1/mcp"))
        .header(CONTENT_TYPE, "application/json")
        .header(ACCEPT, "application/json, text/event-stream")
        .header(AUTHORIZATION, format!("Bearer {token}"))
        .header("mcp-session-id", session_id)
        .json(body)
        .send()
        .await
        .expect("Failed to send MCP request")
}

/// Initialize an MCP session and return the session ID.
async fn init_mcp_session(client: &reqwest::Client, addr: SocketAddr, token: &str) -> String {
    let init = json!({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-03-26",
            "capabilities": {},
            "clientInfo": { "name": "test", "version": "0.1" }
        }
    });
    let res = mcp_post(client, addr, &init, Some(token)).await;
    assert_eq!(res.status(), StatusCode::OK);

    let session_id = res
        .headers()
        .get("mcp-session-id")
        .expect("missing mcp-session-id header")
        .to_str()
        .unwrap()
        .to_string();

    let initialized = json!({
        "jsonrpc": "2.0",
        "method": "notifications/initialized"
    });
    let _ = mcp_post_with_session(client, addr, &initialized, token, &session_id).await;

    session_id
}

/// Extract JSON-RPC result from SSE response body.
fn extract_sse_json(body_text: &str) -> serde_json::Value {
    let json_str = body_text
        .lines()
        .filter_map(|l| l.strip_prefix("data:"))
        .map(str::trim)
        .find(|s| s.starts_with('{'))
        .expect("no SSE data line with JSON found in response");
    serde_json::from_str(json_str).expect("invalid JSON in SSE data")
}

