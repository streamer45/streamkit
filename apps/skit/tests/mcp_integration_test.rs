//! Integration tests for the embedded MCP (Model Context Protocol) server.
//!
//! These tests exercise the MCP endpoint through real HTTP requests,
//! verifying auth enforcement, tool routing, and permission filtering.
//!
//! Requires the `mcp` feature: `cargo test --features mcp -p streamkit-server`

#![cfg(feature = "mcp")]
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::disallowed_macros,
    clippy::uninlined_format_args
)]

use axum::http::StatusCode;
use reqwest::header::{ACCEPT, AUTHORIZATION, CONTENT_TYPE};
use serde_json::json;
use std::net::SocketAddr;
use std::sync::Arc;
use streamkit_server::Config;
use tempfile::TempDir;
use tokio::net::TcpListener;
use tokio::time::Duration;

/// Start a test server with MCP enabled and built-in auth.
///
/// # Panics
///
/// Panics if the TCP listener cannot be bound (including `PermissionDenied`).
async fn start_mcp_server() -> (SocketAddr, tokio::task::JoinHandle<()>, String, TempDir) {
    let listener =
        TcpListener::bind("127.0.0.1:0").await.expect("Failed to bind test server listener");
    let addr = listener.local_addr().unwrap();
    let temp_dir = TempDir::new().unwrap();

    let mut config = Config::default();
    config.mcp.enabled = true;
    config.auth.mode = streamkit_server::config::AuthMode::Enabled;
    config.auth.state_dir = temp_dir.path().to_string_lossy().to_string();

    let auth_state = streamkit_server::auth::AuthState::new(&config.auth, true)
        .await
        .expect("Failed to init auth state");
    let auth_state = Arc::new(auth_state);

    let admin_token_path = temp_dir.path().join("admin.token");
    let admin_token =
        tokio::fs::read_to_string(&admin_token_path).await.expect("Missing admin.token");
    let admin_token = admin_token.trim().to_string();

    let (app, _state) = streamkit_server::server::create_app(config, Some(auth_state));
    let server_handle = tokio::spawn(async move {
        axum::serve(listener, app.into_make_service()).await.unwrap();
    });

    tokio::time::sleep(Duration::from_millis(100)).await;
    (addr, server_handle, admin_token, temp_dir)
}

/// Start a test server with restricted permissions (no create_sessions).
async fn start_restricted_mcp_server() -> (SocketAddr, tokio::task::JoinHandle<()>, String, TempDir)
{
    let listener =
        TcpListener::bind("127.0.0.1:0").await.expect("Failed to bind test server listener");
    let addr = listener.local_addr().unwrap();
    let temp_dir = TempDir::new().unwrap();

    let mut config = Config::default();
    config.mcp.enabled = true;
    config.auth.mode = streamkit_server::config::AuthMode::Enabled;
    config.auth.state_dir = temp_dir.path().to_string_lossy().to_string();

    // Restrict the admin role: disable create_sessions.
    // The admin token generated by AuthState::new has role="admin".
    if let Some(admin_perms) = config.permissions.roles.get_mut("admin") {
        admin_perms.create_sessions = false;
    }

    let auth_state = streamkit_server::auth::AuthState::new(&config.auth, true)
        .await
        .expect("Failed to init auth state");
    let auth_state = Arc::new(auth_state);

    let admin_token_path = temp_dir.path().join("admin.token");
    let admin_token =
        tokio::fs::read_to_string(&admin_token_path).await.expect("Missing admin.token");
    let admin_token = admin_token.trim().to_string();

    let (app, _state) = streamkit_server::server::create_app(config, Some(auth_state));
    let server_handle = tokio::spawn(async move {
        axum::serve(listener, app.into_make_service()).await.unwrap();
    });

    tokio::time::sleep(Duration::from_millis(100)).await;
    (addr, server_handle, admin_token, temp_dir)
}

/// Send a JSON-RPC request to the MCP endpoint.
async fn mcp_post(
    client: &reqwest::Client,
    addr: SocketAddr,
    body: &serde_json::Value,
    auth_header: Option<&str>,
) -> reqwest::Response {
    let mut req = client
        .post(format!("http://{addr}/api/v1/mcp"))
        .header(CONTENT_TYPE, "application/json")
        .header(ACCEPT, "application/json, text/event-stream")
        .json(body);

    if let Some(token) = auth_header {
        req = req.header(AUTHORIZATION, format!("Bearer {token}"));
    }

    req.send().await.expect("Failed to send MCP request")
}

/// Send a JSON-RPC request with a session ID.
async fn mcp_post_with_session(
    client: &reqwest::Client,
    addr: SocketAddr,
    body: &serde_json::Value,
    token: &str,
    session_id: &str,
) -> reqwest::Response {
    client
        .post(format!("http://{addr}/api/v1/mcp"))
        .header(CONTENT_TYPE, "application/json")
        .header(ACCEPT, "application/json, text/event-stream")
        .header(AUTHORIZATION, format!("Bearer {token}"))
        .header("mcp-session-id", session_id)
        .json(body)
        .send()
        .await
        .expect("Failed to send MCP request")
}

/// Initialize an MCP session and return the session ID.
async fn init_mcp_session(client: &reqwest::Client, addr: SocketAddr, token: &str) -> String {
    let init = json!({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-03-26",
            "capabilities": {},
            "clientInfo": { "name": "test", "version": "0.1" }
        }
    });
    let res = mcp_post(client, addr, &init, Some(token)).await;
    assert_eq!(res.status(), StatusCode::OK);

    let session_id = res
        .headers()
        .get("mcp-session-id")
        .expect("missing mcp-session-id header")
        .to_str()
        .unwrap()
        .to_string();

    // Send initialized notification
    let initialized = json!({
        "jsonrpc": "2.0",
        "method": "notifications/initialized"
    });
    let _ = mcp_post_with_session(client, addr, &initialized, token, &session_id).await;

    session_id
}

/// Extract JSON-RPC result from SSE response body.
fn extract_sse_json(body_text: &str) -> serde_json::Value {
    let json_str = body_text
        .lines()
        .filter_map(|l| l.strip_prefix("data:"))
        .map(str::trim)
        .find(|s| s.starts_with('{'))
        .expect("no SSE data line with JSON found in response");
    serde_json::from_str(json_str).expect("invalid JSON in SSE data")
}

